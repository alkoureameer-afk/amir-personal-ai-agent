def decode_mime_header(
    value: str,
) -> str:
    if not value:
        return ""

    try:
        parts = decode_header(value)

        result = ""

        for part, encoding in parts:
            if isinstance(part, bytes):
                result += part.decode(
                    encoding or "utf-8",
                    errors="replace",
                )
            else:
                result += part

        return result

    except Exception:
        return value


def repair_mojibake(
    text: str,
) -> str:
    if not text:
        return ""

    candidates = [text]

    for source_encoding in [
        "latin1",
        "cp1252",
    ]:
        try:
            fixed = (
                text
                .encode(
                    source_encoding,
                    errors="ignore",
                )
                .decode(
                    "utf-8",
                    errors="ignore",
                )
            )

            if fixed:
                candidates.append(fixed)

        except Exception:
            pass

    def score(value: str) -> int:
        bad = (
            value.count("Ø")
            + value.count("Ù")
            + value.count("Ã")
            + value.count("�")
        )

        arabic = sum(
            1
            for char in value
            if "\u0600"
            <= char
            <= "\u06ff"
        )

        return (
            arabic * 3
            - bad * 5
        )

    return max(
        candidates,
        key=score,
    )


def clean_header(
    value: str,
) -> str:
    return repair_mojibake(
        decode_mime_header(value)
    )


def get_header(
    headers: list,
    name: str,
) -> str:
    for header in headers:
        if (
            header
            .get("name", "")
            .lower()
            == name.lower()
        ):
            return clean_header(
                header.get("value", "")
            )

    return ""


