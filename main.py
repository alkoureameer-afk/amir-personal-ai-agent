async def build_agent_reply(
    user_message: str,
    user_id: str = "",
) -> str:

    user_message = (
        user_message
        or ""
    ).strip()

    normalized_command = (
        user_message.lower()
    )

    pending = (
        pending_outbound_messages
        .get(user_id)
    )

    # =====================================================
    # Confirm Pending WhatsApp Send
    # =====================================================

    confirmation_words = [
        "موافق",
        "وافق",
        "نعم",
        "نعم ارسل",
        "نعم أرسل",
        "ارسل",
        "أرسل",
        "تأكيد",
        "تاكيد",
        "اكد",
        "أكد",
        "موافق ارسل",
        "موافق أرسل",
        "موافق ارسل الرسالة",
        "موافق أرسل الرسالة",
        "نعم ارسلها",
        "نعم أرسلها",
        "confirm",
    ]

    is_confirmation = any(
        (
            normalized_command == word
            or normalized_command.startswith(
                word + " "
            )
        )
        for word in confirmation_words
    )

    if pending and is_confirmation:
        to_number = pending.get("to")
        message_text = pending.get("text")

        print(
            "User confirmed outbound WhatsApp:",
            user_id,
            "to:",
            to_number,
        )

        success = await send_whatsapp_message(
            to_number,
            message_text,
        )

        if success:
            pending_outbound_messages.pop(
                user_id,
                None,
            )

            return (
                "تم إرسال الرسالة بنجاح ✅\n\n"
                f"إلى: +{to_number}"
            )

        return (
            "حاولت إرسال الرسالة ولكن "
            "WhatsApp رفض الإرسال ❌\n\n"
            "اكتب «موافق» للمحاولة مرة أخرى "
            "أو «إلغاء»."
        )

    # =====================================================
    # Cancel Pending Send
    # =====================================================

    cancel_words = [
        "إلغاء",
        "الغاء",
        "ألغي",
        "الغي",
        "إلغي",
        "cancel",
    ]

    if (
        pending
        and normalized_command
        in cancel_words
    ):
        pending_outbound_messages.pop(
            user_id,
            None,
        )

        return (
            "تم إلغاء إرسال الرسالة ✅"
        )

    # =====================================================
    # Create New Outbound Send
    # =====================================================

    outbound = parse_whatsapp_send_command(
        user_message
    )

    if outbound:
        to_number, message_text = outbound

        if (
            len(to_number) < 8
            or len(to_number) > 15
        ):
            return (
                "رقم الهاتف غير صحيح.\n\n"
                "اكتب الرقم بالصيغة الدولية.\n"
                "مثال:\n"
                "+9705XXXXXXXX"
            )

        if not message_text:
            return (
                "لم تكتب نص الرسالة."
            )

        if len(message_text) > 3500:
            return (
                "الرسالة طويلة جدًا. "
                "اختصرها ثم حاول مرة أخرى."
            )

        pending_outbound_messages[
            user_id
        ] = {
            "to": to_number,
            "text": message_text,
        }

        print(
            "Outbound WhatsApp pending:",
            user_id,
            "to:",
            to_number,
        )

        return (
            "جاهز للإرسال 📤\n\n"
            f"إلى: +{to_number}\n\n"
            "الرسالة:\n"
            f"{message_text}\n\n"
            "لم يتم الإرسال بعد.\n\n"
            "اكتب «موافق» للإرسال "
            "أو «إلغاء» لإلغاء العملية."
        )

    # =====================================================
    # Gmail
    # =====================================================

    if is_gmail_request(user_message):
        try:
            messages = await get_gmail_summaries(
                limit=5
            )

            if not messages:
                return (
                    "لم أجد رسائل في Gmail."
                )

            blocks = []

            for index, item in enumerate(
                messages,
                start=1,
            ):
                blocks.append(
                    (
                        f"رسالة {index}\n"
                        f"المرسل: "
                        f"{item.get('from', '')}\n"
                        f"العنوان: "
                        f"{item.get('subject', '')}\n"
                        f"التاريخ: "
                        f"{item.get('date', '')}\n"
                        f"المقتطف: "
                        f"{item.get('snippet', '')}"
                    )
                )

            gmail_context = "\n\n".join(
                blocks
            )

            memory_context = ""

            if user_id:
                memory_context = (
                    await build_conversation_context(
                        user_id
                    )
                )

            prompt = f"""
أنت وكيل أمير الشخصي.

طلب المستخدم:
{user_message}

هذه بيانات حقيقية تم جلبها الآن من Gmail:
{gmail_context}

المحادثة السابقة:
{memory_context}

تعليمات مهمة:
- استخدم بيانات Gmail الموجودة أعلاه فقط.
- لا تخترع رسائل أو مرسلين.
- لا ترسل أي بريد.
- لا تحذف أي بريد.
- لا تعدل أي بريد.
- Gmail للقراءة فقط.
- إذا طلب آخر رسالتين فقط، اعرض رسالتين فقط.
- إذا طلب اسم المرسل والعنوان فقط، اعرضهما فقط.
- أجب بالعربية بشكل واضح ومختصر.
"""

            reply = await run_agent(prompt)

            return (
                reply
                or (
                    "تم جلب Gmail ولكن "
                    "تعذر إنشاء الرد."
                )
            )

        except Exception as exc:
            print(
                "Gmail processing error:",
                repr(exc),
            )

            return (
                "حدث خطأ أثناء فحص Gmail. "
                "لم يتم إرسال أو حذف أي بريد."
            )

    # =====================================================
    # Normal AI Conversation
    # =====================================================

    try:
        context = ""

        if user_id:
            context = (
                await build_conversation_context(
                    user_id
                )
            )

        prompt = f"""
أنت وكيل أمير الشخصي.

المحادثة السابقة:
{context}

رسالة المستخدم الحالية:
{user_message}

تعليمات:
- أجب بالعربية بشكل طبيعي وواضح.
- لا تدّع أنك أرسلت WhatsApp إلا إذا قام النظام بتنفيذ الإرسال فعليًا.
- إذا أراد المستخدم إرسال رسالة WhatsApp، اطلب منه استخدام الصيغة:
  أرسل إلى +رقم_الهاتف رسالة: نص الرسالة
- بعد إنشاء طلب الإرسال، يحتاج إلى كتابة «موافق».
- لا تقل إن WhatsApp غير متاح بشكل عام، لأن التطبيق يحتوي على وظيفة إرسال حقيقية.
"""

        reply = await run_agent(prompt)

        return (
            reply
            or "تعذر إنشاء الرد."
        )

    except Exception as exc:
        print(
            "Agent error:",
            repr(exc),
        )

        return (
            "حدث خطأ مؤقت أثناء معالجة طلبك."
        )


