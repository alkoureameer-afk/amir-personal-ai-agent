@app.post(
    "/whatsapp/webhook"
)
async def whatsapp_webhook(
    request: Request,
    background_tasks: BackgroundTasks,
):

    try:

        payload = await request.json()

        entries = payload.get(
            "entry",
            [],
        )

        for entry in entries:

            changes = entry.get(
                "changes",
                [],
            )

            for change in changes:

                value = change.get(
                    "value",
                    {},
                )

                messages = value.get(
                    "messages",
                    [],
                )

                if not messages:

                    continue

                for message in messages:

                    if (
                        message.get(
                            "type"
                        )
                        != "text"
                    ):

                        continue

                    message_id = message.get(
                        "id",
                        "",
                    )

                    if (
                        message_id
                        and not remember_whatsapp_message(
                            message_id
                        )
                    ):

                        print(
                            "Duplicate WhatsApp "
                            "message ignored:",
                            message_id,
                        )

                        continue

                    sender = message.get(
                        "from",
                        "",
                    )

                    text = (
                        message
                        .get(
                            "text",
                            {},
                        )
                        .get(
                            "body",
                            "",
                        )
                        .strip()
                    )

                    if not sender:

                        continue

                    if not text:

                        continue

                    background_tasks.add_task(
                        process_whatsapp_message,
                        sender,
                        text,
                        message_id,
                    )

    except Exception as exc:

        print(
            "WhatsApp webhook error:",
            repr(exc),
        )

    # Return quickly to Meta
    return {
        "status": "received"
    }


