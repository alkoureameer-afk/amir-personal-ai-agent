async def gmail_request(
    method: str,
    url: str,
    **kwargs,
):
    token = await get_access_token()

    headers = kwargs.pop(
        "headers",
        {},
    )

    headers[
        "Authorization"
    ] = f"Bearer {token}"

    async with httpx.AsyncClient(
        timeout=30.0
    ) as client:
        response = await client.request(
            method,
            url,
            headers=headers,
            **kwargs,
        )

    if response.status_code == 401:
        google_tokens.pop(
            "access_token",
            None,
        )

        token = await refresh_access_token()

        headers[
            "Authorization"
        ] = f"Bearer {token}"

        async with httpx.AsyncClient(
            timeout=30.0
        ) as client:
            response = await client.request(
                method,
                url,
                headers=headers,
                **kwargs,
            )

    return response


