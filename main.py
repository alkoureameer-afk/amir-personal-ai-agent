async def get_memory(
    user_id: str,
    limit: int = MAX_CONVERSATION_MESSAGES,
):

    if not user_id:

        return []

    if not db_pool:

        return []

    try:

        async with db_pool.acquire() as conn:

            rows = await conn.fetch(
                """
                select
                    role,
                    content,
                    created_at

                from agent_memory

                where phone_number = $1

                order by created_at desc

                limit $2
                """,
                user_id,
                limit,
            )

        result = []

        for row in reversed(rows):

            result.append(
                {
                    "role": row["role"],
                    "content": row["content"],
                }
            )

        return result

    except Exception as exc:

        print(
            "Memory read error:",
            repr(exc),
        )

        return []


