# Gmail API Request
# =========================================================

async def gmail_request(
    method: str,
    url: str,
    **kwargs,
):

    access_token = await get_access_token()

    headers = kwargs.pop(
        "headers",
        {},
    )

    headers[
        "Authorization"
    ] = (
        f"Bearer {access_token}"
    )

    async with httpx.AsyncClient(
        timeout=30.0
    ) as client:

        response = await client.request(
            method,
            url,
            headers=headers,
            **kwargs,
        )

    if response.status_code == 401:

        google_tokens.pop(
            "access_token",
            None,
        )

        access_token = (
            await refresh_access_token()
        )

        headers[
            "Authorization"
        ] = (
            f"Bearer {access_token}"
        )

        async with httpx.AsyncClient(
            timeout=30.0
        ) as client:

            response = await client.request(
                method,
                url,
                headers=headers,
                **kwargs,
            )

    return response


