async def refresh_access_token() -> str:

    refresh_token = (
        google_tokens.get(
            "refresh_token"
        )
        or GOOGLE_REFRESH_TOKEN
    )

    if not refresh_token:

        raise HTTPException(
            status_code=401,
            detail=(
                "Connect Gmail first"
            ),
        )

    if (
        not GOOGLE_CLIENT_ID
        or not GOOGLE_CLIENT_SECRET
    ):

        raise HTTPException(
            status_code=500,
            detail=(
                "Google OAuth "
                "is not configured"
            ),
        )

    async with httpx.AsyncClient(
        timeout=30.0
    ) as client:

        response = await client.post(
            "https://oauth2.googleapis.com/token",

            data={
                "client_id": (
                    GOOGLE_CLIENT_ID
                ),

                "client_secret": (
                    GOOGLE_CLIENT_SECRET
                ),

                "refresh_token": (
                    refresh_token
                ),

                "grant_type": (
                    "refresh_token"
                ),
            },
        )

    if response.status_code != 200:

        print(
            "Google token refresh failed:",
            response.status_code,
            response.text,
        )

        raise HTTPException(
            status_code=401,
            detail="تعذر تجديد جلسة Gmail",
        )

    token_data = response.json()

    access_token = token_data.get(
        "access_token"
    )

    if not access_token:

        raise HTTPException(
            status_code=401,
            detail=(
                "Google did not return "
                "an access token"
            ),
        )

    google_tokens[
        "access_token"
    ] = access_token

    google_tokens[
        "refresh_token"
    ] = refresh_token

    return access_token


async def get_access_token() -> str:

    access_token = google_tokens.get(
        "access_token"
    )

    if access_token:
        return access_token

    return await refresh_access_token()


