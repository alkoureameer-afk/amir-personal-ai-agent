@app.get(
    "/gmail/messages"
)
async def gmail_messages(
    max_results: int = 10,
):

    max_results = max(
        1,
        min(
            max_results,
            50,
        ),
    )

    response = await gmail_request(
        "GET",
        "https://gmail.googleapis.com/gmail/v1/users/me/messages",
        params={
            "maxResults": max_results,
            "q": "newer_than:1d",
        },
    )

    if response.status_code != 200:

        raise HTTPException(
            status_code=response.status_code,
            detail="Failed to fetch Gmail messages",
        )

    message_refs = response.json().get(
        "messages",
        [],
    )

    messages = []

    for message_ref in message_refs:

        message_id = message_ref.get(
            "id"
        )

        detail_response = await gmail_request(
            "GET",
            "https://gmail.googleapis.com/gmail/v1/users/me/messages/"
            + message_id,
            params={
                "format": "full",
            },
        )

        if detail_response.status_code != 200:
            continue

        data = detail_response.json()

        payload = data.get(
            "payload",
            {},
        )

        headers = payload.get(
            "headers",
            [],
        )

        messages.append(
            {
                "id": message_id,
                "thread_id": data.get(
                    "threadId"
                ),
                "from": get_header(
                    headers,
                    "From",
                ),
                "to": get_header(
                    headers,
                    "To",
                ),
                "subject": get_header(
                    headers,
                    "Subject",
                ),
                "date": get_header(
                    headers,
                    "Date",
                ),
                "snippet": data.get(
                    "snippet",
                    "",
                ),
            }
        )

    return {
        "count": len(messages),
        "messages": messages,
    }


