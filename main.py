def normalize_phone_number(
    phone: str,
) -> str:

    """
    WhatsApp Cloud API expects:
    country code + number
    without + or spaces.

    Example:
    +9705XXXXXXXX
    becomes:
    9705XXXXXXXX
    """

    return re.sub(
        r"\D",
        "",
        phone or "",
    )


def parse_whatsapp_send_command(
    text: str,
):

    """
    Supported examples:

    أرسل إلى +9705XXXXXXXX رسالة: مرحبا
    ارسل الى 9705XXXXXXXX: مرحبا
    أرسل ل 9705XXXXXXXX مرحبا
    """

    text = (
        text
        or ""
    ).strip()

    pattern = (
        r"^(?:أرسل|ارسل)\s+"
        r"(?:إلى|الى|ل|لـ)\s*"
        r"(\+?\d{8,15})"
        r"\s*(?:رسالة)?\s*[:：]?\s*"
        r"(.+)$"
    )

    match = re.match(
        pattern,
        text,
        flags=(
            re.IGNORECASE
            | re.DOTALL
        ),
    )

    if not match:

        return None

    phone = normalize_phone_number(
        match.group(1)
    )

    message = (
        match.group(2)
        .strip()
    )

    if (
        not phone
        or not message
    ):

        return None

    return (
        phone,
        message,
    )


