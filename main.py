def is_gmail_request(
    user_message: str,
) -> bool:

    text = (
        user_message
        .lower()
        .strip()
    )

    gmail_keywords = [
        "gmail",
        "جيميل",
        "البريد",
        "بريدي",
        "الايميل",
        "الإيميل",
        "ايميلي",
        "إيميلي",
        "رسائلي",
        "رسائل البريد",
        "افحص البريد",
        "افحص gmail",
        "افحص جيميل",
        "اخر رسائلي",
        "آخر رسائلي",
        "لخص رسائلي",
        "لخّص رسائلي",
    ]

    return any(
        keyword in text
        for keyword in gmail_keywords
    )


