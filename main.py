@app.post("/chat")
async def chat(
    request: ChatRequest,
):

    text = (
        request.message
        .strip()
    )

    if not text:

        raise HTTPException(
            status_code=400,
            detail="Message is required",
        )

    answer = await build_agent_reply(
        text,
        "web-user",
    )

    await save_memory(
        "web-user",
        "user",
        text,
    )

    await save_memory(
        "web-user",
        "assistant",
        answer,
    )

    return {
        "reply":
            answer
    }


