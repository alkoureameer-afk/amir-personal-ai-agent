async def refresh_access_token() -> str:
    refresh_token = (
        google_tokens.get(
            "refresh_token"
        )
        or GOOGLE_REFRESH_TOKEN
    )

    if not refresh_token:
        raise HTTPException(
            status_code=401,
            detail="Connect Gmail first",
        )

    if (
        not GOOGLE_CLIENT_ID
        or not GOOGLE_CLIENT_SECRET
    ):
        raise HTTPException(
            status_code=500,
            detail=(
                "Google OAuth is not configured"
            ),
        )

    async with httpx.AsyncClient(
        timeout=30.0
    ) as client:
        response = await client.post(
            "https://oauth2.googleapis.com/token",
            data={
                "client_id": (
                    GOOGLE_CLIENT_ID
                ),
                "client_secret": (
                    GOOGLE_CLIENT_SECRET
                ),
                "refresh_token": (
                    refresh_token
                ),
                "grant_type": (
                    "refresh_token"
                ),
            },
        )

    if response.status_code != 200:
        print(
            "Google token refresh failed:",
            response.status_code,
            response.text[:300],
        )

        raise HTTPException(
            status_code=401,
            detail="تعذر تجديد جلسة Gmail",
        )

    data = response.json()

    access_token = data.get(
        "access_token"
    )

    if not access_token:
        raise HTTPException(
            status_code=401,
            detail=(
                "Google access token missing"
            ),
        )

    google_tokens[
        "access_token"
    ] = access_token

    google_tokens[
        "refresh_token"
    ] = refresh_token

    return access_token


async def get_access_token() -> str:
    token = google_tokens.get(
        "access_token"
    )

    if token:
        return token

    return await refresh_access_token()


@app.get("/auth/google")
def google_login():
    if not GOOGLE_CLIENT_ID:
        raise HTTPException(
            status_code=500,
            detail="GOOGLE_CLIENT_ID missing",
        )

    state = secrets.token_urlsafe(32)

    pending_states.add(state)

    params = {
        "client_id": GOOGLE_CLIENT_ID,
        "redirect_uri": REDIRECT_URI,
        "response_type": "code",
        "scope": GMAIL_SCOPE,
        "access_type": "offline",
        "prompt": "consent",
        "state": state,
    }

    url = (
        "https://accounts.google.com/"
        "o/oauth2/v2/auth?"
        + urlencode(params)
    )

    return RedirectResponse(url)


@app.get(
    "/auth/google/callback"
)
async def google_callback(
    code: str,
    state: str,
):
    if state not in pending_states:
        raise HTTPException(
            status_code=400,
            detail="Invalid OAuth state",
        )

    pending_states.remove(state)

    async with httpx.AsyncClient(
        timeout=30.0
    ) as client:
        response = await client.post(
            "https://oauth2.googleapis.com/token",
            data={
                "client_id": (
                    GOOGLE_CLIENT_ID
                ),
                "client_secret": (
                    GOOGLE_CLIENT_SECRET
                ),
                "code": code,
                "grant_type": (
                    "authorization_code"
                ),
                "redirect_uri": (
                    REDIRECT_URI
                ),
            },
        )

    if response.status_code != 200:
        print(
            "Google authorization failed:",
            response.status_code,
            response.text[:300],
        )

        raise HTTPException(
            status_code=400,
            detail=(
                "Google authorization failed"
            ),
        )

    data = response.json()

    access_token = data.get(
        "access_token"
    )

    refresh_token = data.get(
        "refresh_token"
    )

    if access_token:
        google_tokens[
            "access_token"
        ] = access_token

    if refresh_token:
        google_tokens[
            "refresh_token"
        ] = refresh_token

    return PlainTextResponse(
        "Gmail connected successfully"
    )


