async def save_memory(
    user_id: str,
    role: str,
    content: str,
):
    if not user_id or not role or not content:
        return

    if not db_pool:
        return

    try:
        async with db_pool.acquire() as conn:
            await conn.execute(
                """
                insert into agent_memory (
                    phone_number,
                    role,
                    content
                )
                values ($1, $2, $3)
                """,
                user_id,
                role,
                content,
            )

    except Exception as exc:
        print(
            "Memory save error:",
            repr(exc),
        )


async def get_memory(
    user_id: str,
    limit: int = MAX_CONVERSATION_MESSAGES,
):
    if not user_id or not db_pool:
        return []

    try:
        async with db_pool.acquire() as conn:
            rows = await conn.fetch(
                """
                select
                    role,
                    content,
                    created_at

                from agent_memory

                where phone_number = $1

                order by created_at desc

                limit $2
                """,
                user_id,
                limit,
            )

        return [
            {
                "role": row["role"],
                "content": row["content"],
            }
            for row in reversed(rows)
        ]

    except Exception as exc:
        print(
            "Memory read error:",
            repr(exc),
        )

        return []


async def build_conversation_context(
    user_id: str,
) -> str:
    history = await get_memory(user_id)

    if not history:
        return ""

    lines = []

    for item in history:
        if item.get("role") == "user":
            label = "المستخدم"
        else:
            label = "المساعد"

        lines.append(
            f"{label}: {item.get('content', '')}"
        )

    return "\n".join(lines)


