async def send_whatsapp_message(
    to: str,
    text: str,
):

    if (
        not WHATSAPP_ACCESS_TOKEN
        or not WHATSAPP_PHONE_NUMBER_ID
    ):

        print(
            "WhatsApp configuration missing"
        )

        return False

    to = normalize_phone_number(
        to
    )

    if not to:

        return False

    if not text:

        return False

    url = (
        "https://graph.facebook.com/v20.0/"
        + WHATSAPP_PHONE_NUMBER_ID
        + "/messages"
    )

    headers = {
        "Authorization":
            "Bearer "
            + WHATSAPP_ACCESS_TOKEN,

        "Content-Type":
            "application/json",
    }

    payload = {
        "messaging_product":
            "whatsapp",

        "recipient_type":
            "individual",

        "to":
            to,

        "type":
            "text",

        "text": {
            "preview_url":
                False,

            "body":
                text[:4000],
        },
    }

    try:

        async with httpx.AsyncClient(
            timeout=30.0
        ) as client:

            response = await client.post(
                url,
                headers=headers,
                json=payload,
            )

        if (
            response.status_code
            >= 300
        ):

            print(
                "WhatsApp send FAILED:",
                response.status_code,
                response.text[:1000],
            )

            return False

        print(
            "WhatsApp message sent:",
            to,
        )

        print(
            "Meta response:",
            response.text[:500],
        )

        return True

    except Exception as exc:

        print(
            "WhatsApp send exception:",
            repr(exc),
        )

        return False


