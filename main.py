# =========================================================
# Gmail Summaries
# =========================================================

async def get_gmail_summaries(
    limit: int = 5,
):

    limit = max(
        1,
        min(
            limit,
            10,
        ),
    )

    response = await gmail_request(
        "GET",
        (
            "https://gmail.googleapis.com/"
            "gmail/v1/users/me/messages"
        ),
        params={
            "maxResults": limit,
        },
    )

    if response.status_code != 200:

        print(
            "Gmail list error:",
            response.status_code,
        )

        raise HTTPException(
            status_code=response.status_code,
            detail=(
                "Failed to fetch Gmail messages"
            ),
        )

    message_refs = (
        response
        .json()
        .get(
            "messages",
            [],
        )
    )

    messages = []

    for message_ref in message_refs:

        message_id = message_ref.get(
            "id"
        )

        if not message_id:

            continue

        detail_response = await gmail_request(
            "GET",
            (
                "https://gmail.googleapis.com/"
                "gmail/v1/users/me/messages/"
                + message_id
            ),
            params={
                "format": "metadata",

                "metadataHeaders": [
                    "From",
                    "To",
                    "Subject",
                    "Date",
                ],
            },
        )

        if (
            detail_response.status_code
            != 200
        ):

            continue

        data = detail_response.json()

        payload = data.get(
            "payload",
            {},
        )

        headers = payload.get(
            "headers",
            [],
        )

        messages.append(
            {
                "id": message_id,

                "thread_id": data.get(
                    "threadId"
                ),

                "from": get_header(
                    headers,
                    "From",
                ),

                "to": get_header(
                    headers,
                    "To",
                ),

                "subject": get_header(
                    headers,
                    "Subject",
                ),

                "date": get_header(
                    headers,
                    "Date",
                ),

                "snippet": repair_mojibake(
                    data.get(
                        "snippet",
                        "",
                    )
                ),
            }
        )

    return messages


