def normalize_phone_number(
    phone: str,
) -> str:
    """
    يحول:
    +970568042923
    إلى:
    970568042923
    """

    return re.sub(
        r"\D",
        "",
        phone or "",
    )


def parse_whatsapp_send_command(
    text: str,
):
    """
    أمثلة:

    أرسل إلى +970568042923 رسالة: مرحبا
    ارسل الى 970568042923: مرحبا
    أرسل ل +970568042923 مرحبا
    """

    text = (text or "").strip()

    pattern = (
        r"^(?:أرسل|ارسل)\s+"
        r"(?:إلى|الى|ل|لـ)\s*"
        r"(\+?\d{8,15})"
        r"\s*(?:رسالة)?\s*[:：]?\s*"
        r"(.+)$"
    )

    match = re.match(
        pattern,
        text,
        flags=re.IGNORECASE | re.DOTALL,
    )

    if not match:
        return None

    phone = normalize_phone_number(
        match.group(1)
    )

    message = match.group(2).strip()

    if not phone or not message:
        return None

    return phone, message


# =========================================================
# WhatsApp duplicate protection
# =========================================================

MAX_PROCESSED_WHATSAPP_MESSAGES = 1000

processed_whatsapp_message_ids = set()

processed_whatsapp_message_order = deque()


def remember_whatsapp_message(
    message_id: str,
) -> bool:
    if not message_id:
        return True

    if message_id in processed_whatsapp_message_ids:
        return False

    processed_whatsapp_message_ids.add(
        message_id
    )

    processed_whatsapp_message_order.append(
        message_id
    )

    while (
        len(processed_whatsapp_message_order)
        > MAX_PROCESSED_WHATSAPP_MESSAGES
    ):
        oldest = (
            processed_whatsapp_message_order
            .popleft()
        )

        processed_whatsapp_message_ids.discard(
            oldest
        )

    return True


