MAX_CONVERSATION_MESSAGES = 20


async def save_memory(
    user_id: str,
    role: str,
    content: str,
):

    if (
        not user_id
        or not role
        or not content
    ):

        return

    if not db_pool:

        print(
            "Memory not saved: "
            "database unavailable"
        )

        return

    try:

        async with db_pool.acquire() as conn:

            await conn.execute(
                """
                insert into agent_memory (
                    phone_number,
                    role,
                    content
                )

                values (
                    $1,
                    $2,
                    $3
                )
                """,
                user_id,
                role,
                content,
            )

    except Exception as exc:

        print(
            "Memory save error:",
            repr(exc),
        )


async def get_memory(
    user_id: str,
    limit: int = MAX_CONVERSATION_MESSAGES,
):

    if not user_id:

        return []

    if not db_pool:

        return []

    try:

        async with db_pool.acquire() as conn:

            rows = await conn.fetch(
                """
                select
                    role,
                    content,
                    created_at

                from agent_memory

                where phone_number = $1

                order by created_at desc

                limit $2
                """,
                user_id,
                limit,
            )

        result = []

        for row in reversed(rows):

            result.append(
                {
                    "role": row["role"],
                    "content": row["content"],
                }
            )

        return result

    except Exception as exc:

        print(
            "Memory read error:",
            repr(exc),
        )

        return []


async def build_conversation_context(
    user_id: str,
) -> str:

    history = await get_memory(
        user_id
    )

    if not history:

        return ""

    lines = []

    for item in history:

        role = item.get(
            "role"
        )

        content = item.get(
            "content",
            "",
        )

        if role == "user":

            label = "المستخدم"

        else:

            label = "المساعد"

        lines.append(
            f"{label}: {content}"
        )

    return "\n".join(
        lines
    )


# =========================================================
# WhatsApp duplicate protection
# =========================================================

MAX_PROCESSED_WHATSAPP_MESSAGES = 1000

processed_whatsapp_message_ids = set()

processed_whatsapp_message_order = deque()


def remember_whatsapp_message(
    message_id: str,
) -> bool:

    if not message_id:

        return True

    if (
        message_id
        in processed_whatsapp_message_ids
    ):

        return False

    processed_whatsapp_message_ids.add(
        message_id
    )

    processed_whatsapp_message_order.append(
        message_id
    )

    while (
        len(
            processed_whatsapp_message_order
        )
        > MAX_PROCESSED_WHATSAPP_MESSAGES
    ):

        oldest_id = (
            processed_whatsapp_message_order
            .popleft()
        )

        processed_whatsapp_message_ids.discard(
            oldest_id
        )

    return True


